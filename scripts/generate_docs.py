#!/usr/bin/env python3
"""Generate docs/tools.md from src/*.py docstrings.

Scans for @mcp.tool / @mcp.resource / @mcp.prompt and extracts docstrings.
Writes markdown table per module for MkDocs.
"""

import ast
import re
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
SRC = BASE / "src"
OUT = BASE / "docs" / "tools.md"

TOOL_DECOS = {"tool", "resource", "prompt"}


def parse_module(path: Path):
    text = path.read_text(encoding="utf-8")
    tree = ast.parse(text, filename=str(path))
    tools = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for dec in node.decorator_list:
                # Look for @mcp.tool() / @mcp.resource(...) etc.
                deco_str = ast.unparse(dec) if hasattr(ast, "unparse") else ""
                # fallback regex on source segment
                if not deco_str:
                    try:
                        deco_str = ast.get_source_segment(text, dec) or ""
                    except Exception:
                        deco_str = ""
                m = re.search(r"mcp\.(tool|resource|prompt)", deco_str)
                if m:
                    kind = m.group(1)
                    doc = ast.get_docstring(node) or ""
                    # first line
                    first = doc.strip().split("\n")[0] if doc else ""
                    tools.append((kind, node.name, first))
    return tools


def main() -> int:
    modules = sorted(SRC.glob("*.py"))
    total_tools = 0
    total_res = 0
    total_prompts = 0
    lines = []
    lines.append("# Tools Reference\n")
    lines.append("> Auto-generated by `python scripts/generate_docs.py` — do not edit manually.\n")
    lines.append("| Module | Tools | Resources | Prompts |")
    lines.append("|---|---|---|---|")
    per_mod = []
    for mod in modules:
        tools = parse_module(mod)
        t = sum(1 for k, _, _ in tools if k == "tool")
        r = sum(1 for k, _, _ in tools if k == "resource")
        p = sum(1 for k, _, _ in tools if k == "prompt")
        if t or r or p:
            per_mod.append((mod.stem, t, r, p, tools))
            total_tools += t
            total_res += r
            total_prompts += p

    for stem, t, r, p, _ in per_mod:
        lines.append(f"| `{stem}` | {t} | {r} | {p} |")
    lines.append(f"\n**Total:** {total_tools} tools + {total_res} resources + {total_prompts} prompts\n")

    for stem, t, r, p, tools in per_mod:
        if not tools:
            continue
        lines.append(f"\n## `{stem}` — {t} tools\n")
        for kind, name, doc in tools:
            badge = {"tool": "🛠️", "resource": "📦", "prompt": "💬"}[kind]
            lines.append(f"- {badge} **{kind}** `{name}` — {doc}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({total_tools} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
