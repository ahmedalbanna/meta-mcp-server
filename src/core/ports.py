"""Ports (Protocols) for dependency injection and testability."""

from __future__ import annotations

from typing import Any, Protocol


class MetaApiClient(Protocol):
    def get(self, path: str, params: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def post(self, path: str, params: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def delete(self, path: str) -> dict[str, Any]: ...
    def page_get(self, page_id: str, params: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def page_post(self, page_id: str, params: dict[str, Any] | None = None) -> dict[str, Any]: ...


class Storage(Protocol):
    def upsert_daily_fact(self, account_id: str, level: str, entity_id: str, metric_date: str,
                          metric: str, value: float, currency: str | None = None, tz: str = "Asia/Aden") -> None: ...
    def query_daily_facts(self, account_id: str, level: str, entity_id: str,
                          start_date: str, end_date: str, metric: str | None = None) -> list[dict[str, Any]]: ...
    def query_daily_facts_all_entities(self, account_id: str, level: str,
                          start_date: str, end_date: str) -> list[dict[str, Any]]: ...
    def upsert_competitor_snapshot(self, platform: str, handle: str, snapshot_date: str, payload: dict[str, Any]) -> None: ...
    def query_competitor_snapshots(self, platform: str, handle: str, limit: int = 30) -> list[dict[str, Any]]: ...
    def upsert_monthly_snapshot(self, account_id: str, level: str, entity_id: str, year: int, month: int,
                          metric: str, value: float, currency: str | None = None) -> None: ...


class Clock(Protocol):
    def now(self) -> Any: ...
    def today(self) -> str: ...


class Throttle(Protocol):
    def acquire(self) -> None: ...
    def release(self) -> None: ...
